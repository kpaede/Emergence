import esbuild from 'esbuild';
import {readFileSync} from 'node:fs';
import process from 'process';
import { builtinModules } from 'node:module';

const dependencyLicenses = ['i18next-LICENSE.txt', 'argdown-NOTICE.md', 'argdown-LICENSE.txt', 'wasm-graphviz-LICENSE.txt', 'graphviz-LICENSE.txt'].map(file => readFileSync(new URL('./third-party/' + file, import.meta.url), 'utf8')).join('\n\n');
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
/*!
${dependencyLicenses.replace(/\*\//g, '* /')}
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules.filter(name => name !== 'punycode'),
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
